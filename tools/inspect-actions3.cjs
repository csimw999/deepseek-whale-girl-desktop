const fs = require('node:fs')
const model = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
const refs = model.FileReferences || {}
const exprs = (refs.Expressions || []).map(e => e.Name)
const motions = Object.keys(refs.Motions || {})
console.log('表情 (' + exprs.length + '): ' + exprs.join(' | '))
console.log('')
console.log('动作组 (' + motions.length + '): ' + motions.join(', '))
const src = fs.readFileSync(process.argv[3], 'utf8')
const actBlock = src.slice(src.indexOf('const ACTIONS = {'), src.indexOf('function playAction'))
const used = [...actBlock.matchAll(/expr:\s*'([^']+)'/g)].map(m => m[1])
const labels = [...actBlock.matchAll(/label:\s*'([^']+)'/g)].map(m => m[1])
const motionRefs = [...actBlock.matchAll(/motion:\s*'([^']+)'/g)].map(m => m[1])
console.log('')
console.log('动作标签: ' + JSON.stringify(labels))
console.log('用到的表情: ' + JSON.stringify(used))
console.log('用到的 motion: ' + JSON.stringify(motionRefs))
console.log('>>> 缺失表情: ' + JSON.stringify(used.filter(n => !exprs.includes(n))))
console.log('>>> 缺失 motion: ' + JSON.stringify(motionRefs.filter(n => !motions.includes(n))))
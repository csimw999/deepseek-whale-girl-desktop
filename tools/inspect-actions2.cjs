const fs = require('node:fs')
const model = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
const exprs = (model.FileReferences.Expressions || []).map(e => e.Name)
const motions = Object.keys((model.FileReferences.Motions || {}))
console.log('模型表情 (' + exprs.length + '):')
console.log(exprs.join(' | '))
console.log('')
console.log('模型动作组 (' + motions.length + '): ' + motions.join(', '))
const src = fs.readFileSync(process.argv[3], 'utf8')
const actBlock = src.slice(src.indexOf('const ACTIONS = {'), src.indexOf('function playAction'))
const used = [...actBlock.matchAll(/expr:\s*'([^']+)'/g)].map(m => m[1])
const labels = [...actBlock.matchAll(/label:\s*'([^']+)'/g)].map(m => m[1])
const motionRefs = [...actBlock.matchAll(/motion:\s*'([^']+)'/g)].map(m => m[1])
console.log('动作用到的表情: ' + JSON.stringify(used))
console.log('动作标签: ' + JSON.stringify(labels))
console.log('动作用到的 motion: ' + JSON.stringify(motionRefs))
console.log('缺失的表情: ' + JSON.stringify(used.filter(n => !exprs.includes(n))))
console.log('缺失的 motion: ' + JSON.stringify(motionRefs.filter(n => !motions.includes(n))))